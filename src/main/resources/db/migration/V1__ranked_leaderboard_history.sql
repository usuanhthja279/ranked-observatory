create table leaderboard_runs (
 id bigint generated by default as identity primary key,
 act varchar(36) not null, country varchar(2) not null,
 started_at timestamp with time zone not null,
 completed_at timestamp with time zone,
 status varchar(20) not null, pages integer not null default 0,
 players integer not null default 0, error varchar(500)
);
create index idx_leaderboard_runs_latest on leaderboard_runs(act,country,status,id);
create table leaderboard_players (
 run_id bigint not null references leaderboard_runs(id) on delete cascade,
 player_key varchar(300) not null, country varchar(2) not null,
 regional_rank integer not null, rr integer not null,
 tier varchar(40) not null, wins integer not null,
 source_updated_at timestamp with time zone,
 primary key(run_id,player_key)
);
create index idx_leaderboard_player_history on leaderboard_players(player_key,run_id);
