create table observatory_watchlist (
  id bigint generated by default as identity primary key,
  account_id bigint not null references observatory_accounts(id) on delete cascade,
  entity_type varchar(12) not null check (entity_type in ('PLAYER','COUNTRY','REGION','ACT')),
  entity_key varchar(300) not null,
  scope_key varchar(10) not null default 'all',
  display_label varchar(300) not null,
  created_at timestamp with time zone not null default current_timestamp,
  unique(account_id, entity_type, entity_key, scope_key)
);
create index observatory_watchlist_account_created_idx on observatory_watchlist(account_id, created_at desc, id desc);
