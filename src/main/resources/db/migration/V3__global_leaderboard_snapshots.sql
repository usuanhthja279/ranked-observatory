create table global_leaderboard_runs (
 id bigint generated by default as identity primary key,
 act varchar(36) not null, started_at timestamp with time zone not null,
 completed_at timestamp with time zone, status varchar(20) not null,
 pages integer not null default 0, players integer not null default 0,
 raw_rows integer not null default 0, duplicate_rows integer not null default 0,
 uncertain_players integer not null default 0, source varchar(40) not null default 'global',
 coverage_json text, error varchar(500)
);
create index idx_global_runs_latest on global_leaderboard_runs(act,status,id);
create table global_leaderboard_players (
 run_id bigint not null references global_leaderboard_runs(id) on delete cascade,
 region varchar(10) not null, player_key varchar(300) not null,
 display_name varchar(300) not null, country varchar(2),
 global_rank integer, regional_rank integer, rr integer not null,
 tier varchar(40) not null, wins integer not null,
 source_updated_at timestamp with time zone not null,
 rank_ambiguous boolean not null default false,
 stats_ambiguous boolean not null default false,
 primary key(run_id,region,player_key)
);
create index idx_global_player_history on global_leaderboard_players(region,player_key,run_id);
create index idx_global_player_filters on global_leaderboard_players(run_id,region,country);
