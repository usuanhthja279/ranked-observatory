create table mi_import_jobs (
  job_id varchar(36) primary key,
  owner_username varchar(100) not null,
  provider varchar(80) not null,
  status varchar(20) not null,
  requested_matches integer not null,
  response_count integer not null,
  accepted_matches integer not null,
  partial_matches integer not null,
  rejected_matches integer not null,
  export_sha256 char(64) not null,
  parser_version varchar(80) not null,
  created_at timestamp with time zone not null default current_timestamp
);
create index mi_import_jobs_owner_created on mi_import_jobs(owner_username, created_at desc);
create table mi_raw_imports (
  job_id varchar(36) primary key references mi_import_jobs(job_id) on delete cascade,
  gzip_payload bytea not null,
  original_bytes integer not null,
  payload_sha256 char(64) not null,
  purge_after timestamp with time zone not null
);
create table mi_matches (
  provider varchar(80) not null,
  provider_match_id varchar(160) not null,
  created_at timestamp with time zone not null default current_timestamp,
  primary key(provider, provider_match_id)
);
create table mi_match_versions (
  version_id bigint generated by default as identity primary key,
  provider varchar(80) not null,
  provider_match_id varchar(160) not null,
  canonical_sha256 char(64) not null,
  source_response_sha256 char(64) not null,
  parser_version varchar(80) not null,
  quality varchar(32) not null,
  source_started_at timestamp with time zone,
  duration_millis bigint,
  map_name varchar(200),
  mode_name varchar(120),
  act_id varchar(160),
  summary_json text not null,
  canonical_json text not null,
  imported_at timestamp with time zone not null default current_timestamp,
  unique(provider, provider_match_id, canonical_sha256),
  foreign key(provider, provider_match_id) references mi_matches(provider, provider_match_id) on delete cascade
);
create index mi_match_versions_started on mi_match_versions(source_started_at desc);
create table mi_match_teams (
  version_id bigint not null references mi_match_versions(version_id) on delete cascade,
  team_id varchar(160) not null, observed_name varchar(200), rounds_won integer, rounds_lost integer,
  observed_rank varchar(120), has_won boolean, primary key(version_id, team_id)
);
create table mi_match_participants (
  version_id bigint not null references mi_match_versions(version_id) on delete cascade,
  participant_key varchar(600) not null, identity_provider varchar(120), provider_user_id varchar(300),
  observed_riot_id varchar(300), team_id varchar(160), agent varchar(160), identity_confidence varchar(40),
  totals_json text not null, primary key(version_id, participant_key)
);
create index mi_participants_provider_user on mi_match_participants(identity_provider, provider_user_id);
create table mi_match_rounds (
  version_id bigint not null references mi_match_versions(version_id) on delete cascade,
  round_number integer not null, winning_team_id varchar(160), raw_win_method varchar(160),
  plant_evidence_json text, defuse_evidence_json text, detonation_time_raw bigint,
  overtime_by_position boolean not null, primary key(version_id, round_number)
);
create table mi_player_round_stats (
  version_id bigint not null, round_number integer not null, participant_key varchar(600) not null,
  team_id varchar(160), side varchar(80), kills integer, deaths integer, assists integer, damage integer,
  score integer, loadout_value integer, spent_credits integer, remaining_credits integer,
  primary key(version_id, round_number, participant_key),
  foreign key(version_id, round_number) references mi_match_rounds(version_id, round_number) on delete cascade,
  foreign key(version_id, participant_key) references mi_match_participants(version_id, participant_key) on delete cascade
);
create table mi_damage_interactions (
  version_id bigint not null references mi_match_versions(version_id) on delete cascade,
  source_ref varchar(800) not null, round_number integer not null, attacker_key varchar(600), victim_key varchar(600),
  damage integer, headshots integer, bodyshots integer, legshots integer, primary key(version_id, source_ref)
);
create index mi_damage_round on mi_damage_interactions(version_id, round_number);
create table mi_match_events (
  version_id bigint not null references mi_match_versions(version_id) on delete cascade,
  event_id varchar(800) not null, source_ref varchar(800) not null, raw_source_type varchar(160),
  category varchar(80) not null, round_number integer not null, round_time_raw bigint, match_time_raw bigint,
  actor_key varchar(600), target_key varchar(600), assistants_json text not null, weapon_name varchar(200),
  weapon_category varchar(120), damage integer, source_evidence_json text, primary key(version_id, event_id)
);
create index mi_events_round_time on mi_match_events(version_id, round_number, round_time_raw);
create table mi_event_positions (
  version_id bigint not null references mi_match_versions(version_id) on delete cascade,
  position_number integer not null, source_ref varchar(800) not null, snapshot_type varchar(80) not null,
  round_number integer not null, participant_key varchar(600), x double precision, y double precision,
  view_radians double precision, coordinate_space varchar(80) not null, primary key(version_id, position_number)
);
create index mi_event_positions_round on mi_event_positions(version_id, round_number);
create table mi_import_job_matches (
  job_id varchar(36) not null references mi_import_jobs(job_id) on delete cascade,
  entry_number integer not null,
  provider varchar(80) not null,
  provider_match_id varchar(160),
  version_id bigint references mi_match_versions(version_id),
  selected_player_identity varchar(400),
  selected_player_riot_id varchar(300),
  selected_player_team_id varchar(160),
  source_response_sha256 char(64),
  source_captured_at timestamp with time zone,
  quality varchar(32) not null,
  issues_json text not null,
  primary key(job_id, entry_number)
);
create index mi_import_job_matches_lookup on mi_import_job_matches(job_id, provider, provider_match_id);
create index mi_import_job_matches_player on mi_import_job_matches(selected_player_identity);
